st.header("九、行情資料怎麼處理？")
st.markdown(r"""
模擬結果的品質取決於資料。系統在計算前會做這幾件事，並把做了什麼列在主頁結果的最上方：

- **還原沒處理的股票分割**。行情來源對部分台股 ETF 的分割只還原了一段，甚至完全沒還原，資料裡會留下一天 -75% 或 -95% 的假暴跌。
  如果某一天的價格跳動剛好是整數倍（1 拆 4、1 拆 22、7 併 1…），而來源又完全沒有這檔標的的分割紀錄，系統會把接縫之前的價格換算到同一基準。
  來源有提供分割紀錄的標的（多數美股）不會被更動，因為那種情況下大跌比較可能是真的。
- **校正配息的單位**。來源對價格和配息各自只還原到不同日期，所以接縫附近可能有幾筆配息還是分割前的金額，殖利率會突然變成好幾倍。
  系統會找出讓各年殖利率最一致的分界點來換算。如果分界點旁邊剛好有配息特別多或特別少的年份，這個判斷可能差一兩年。
- **提示異常值**。單日漲跌遠超過這檔標的平常的波動、單月配息超過股價 15%、或配息紀錄的開頭有長時間空白，都會列出來。
  系統分不出這是資料錯誤還是真實的極端行情，所以**只提示、不更動**。
- **配息算在除息的那個月**。每月的價格取自扣款日當天（或之後第一個交易日）。一筆配息會算進「價格已經反映除息」的那一期，
  也就是除息日當天或之後的第一個月價；不是單純看它落在哪個日曆月。
- **上市前的歷史可以用替身補**。第一標的上市不久時，可以指定一檔性質相近、上市更久的標的；第一標的上市前的月份直接採用替身當時的實際漲跌與配息。
  這只是近似：替身不是同一檔商品，主頁會顯示兩者重疊期間的相關係數供你判斷。
- **來源連不上時用存檔**。每次成功抓到資料都會存一份；之後如果來源暫時連不上，就改用最近一次的存檔，並在主頁標明存檔日期。
""")
st.warning("這些處理都是根據資料本身的規律做的推斷，不是官方的還原資料。重要決策前，請拿主頁列出的修正項目對照你信任的來源。")

