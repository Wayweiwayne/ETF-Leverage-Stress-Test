st.header("八、跟「定期定額」比較是怎麼比的？")
st.markdown(r"""
系統在每一條模擬路徑裡，都同時跑一個對照組——**定期定額（DCA）**：

- **槓桿策略**：一開始就借一大筆錢全部投入，之後每月承受還款壓力。
- **定期定額**：一開始不借錢，而是把「本來要從薪水拿去繳貸款的那筆錢」，每個月直接拿去買股票。

差別只在於槓桿策略**一開始就持有全部本金**。所以這個比較本質上是在問：「一開始就重壓 vs 慢慢分批買，哪個好？」

要讓這個比較公平，兩邊**自己掏出來的錢必須一樣多**。主頁「進階模擬設定」可以選對照組的投入方式：

- **與槓桿組相同的自掏金額（預設）**：槓桿策略這個月實際從薪水掏了多少，對照組就投入多少。
  如果這個月的貸款是靠配息、緩衝金或賣股票繳掉的，那部分不是你自己掏的錢，對照組也就不會投入。
  槓桿策略破產之後不再繳款，對照組則繼續每月投入「應繳金額與薪水上限取小者」。
- **每月投入整筆應繳金額（舊版算法）**：對照組每月都投入整筆應繳金額，不管薪水上限是多少。
  當應繳金額遠高於薪水上限時（例如月付 6.7 萬、薪水上限 2.5 萬），對照組投入的本金會比槓桿組自掏的多很多，
  比較結果會對槓桿策略不利。
""")
st.warning("**解讀提醒**：在長期上漲的市場裡，「一開始就重壓」通常會贏，因為錢更早進場複利。所以如果你看到槓桿大勝定期定額，要記得——這很大一部分是因為回測那段期間剛好是牛市，不代表借錢投資本身穩贏。")

