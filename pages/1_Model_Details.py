st.header("七、兩種模擬引擎有什麼不同？")
st.markdown(r"""
系統用兩套不同哲學的引擎來評估風險，結果並排顯示：
""")

col1, col2 = st.columns(2)
with col1:
    st.markdown("#### 🅰 歷史滾動 + 情境拼接")
    st.markdown(r"""
    **精神：「過去真的發生過什麼，就拿來測。」**

    把歷史上每一個月都當成一個「假設你那時進場」的起點，看看接下來會怎樣。如果某個起點的歷史資料不夠長（蓋不滿你的貸款年限），不足的未來就用你選的**劇本**（例如 2008 復刻）來補。

    這是一種**確定性的「如果…會怎樣」分析**。
    """)
with col2:
    st.markdown("#### 🅱 蒙地卡羅模擬")
    st.markdown(r"""
    **精神：「理論上可能發生什麼，就測什麼。」**

    從歷史報酬中「一段一段」隨機抽出來、重新拼接成成千上萬種可能的未來，統計其中有多少種會破產。

    一段一段抽（而不是單月亂抽）是為了**保留漲跌的連續性**——因為現實中崩盤通常會連跌好幾個月，不是各月獨立的。
    """)

st.markdown(r"""
> **為什麼要分兩種？** 一種回答「**如果某個特定劇本發生，會怎樣？**」，另一種回答「**各種可能性綜合起來，破產機率多高？**」。兩者互補，但比較基準不同，不要直接把兩個數字混為一談。
""")

