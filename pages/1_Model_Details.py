st.header("一、這個系統到底在算什麼？")
st.markdown(r"""
傳統的投資回測只問一件事：**「買了放著，最後賺多少？」**

這個系統多問了一個更現實的問題：**「如果這筆投資是借錢來的，你每個月都得還貸款，那在還款壓力下，這個策略還活得下去嗎？」**

所以它同時追蹤兩條線：

- **資產端**：你的股票/ETF 值多少錢、領了多少股息。
- **負債端**：每個月要還銀行多少錢。

一旦某個月你「湊不出錢繳貸款」（所有資金來源都用光了還差錢），這個策略就判定**破產**，後面就算市場大漲也跟你無關了。這在財務工程裡叫做「**吸收邊界**」——掉進去就出不來。
""")

st.info("**白話總結**：這不是單純算報酬率，而是在模擬「借錢投資的人，會不會在中途被每月還款壓垮」。")

# ------------------------------------------------------------------
st.header("二、貸款每月要還多少？（對應主頁「貸款與財務參數」）")

st.subheader("一般情況：本息平均攤還")
st.markdown(r"""
假設你借了本金 $L$，年利率是 $R$，那每個月的利率就是 $r = R / 12$。
總共要還 $N$ 個月。每月固定還款金額（PMT）用房貸界的標準公式算：
""")
st.latex(r"PMT = L \times \frac{r(1+r)^{N}}{(1+r)^{N} - 1}")
st.markdown("這個金額每月固定，前期還的大部分是利息，後期才慢慢還到本金。")

st.subheader("寬限期：前幾年只繳利息")
st.markdown(r"""
如果你開了寬限期，前 $g$ 個月只需要付利息：
""")
st.latex(r"PMT_{\text{寬限}} = L \times r")
st.markdown(r"""
寬限期一結束（第 $g$ 個月之後），剩下的本金要在更短的時間 $(N-g)$ 內還完，
所以每月金額會**突然跳高**。這就是為什麼主頁的「初期每月應繳」和「寬限期後每月應繳」常常差很多——這個跳高的衝擊在現實中很容易讓人措手不及。

寬限期一定比貸款總年限短（最長 5 年）。一般信貸通常沒有寬限期，所以選信貸時預設不啟用，需要的話可以自己勾選。
""")

st.subheader("升息情境（對應「模擬升息」）")
st.markdown(r"""
當你打開升息模擬，到了指定的年份，系統會把利率調高，然後用**當下還剩多少本金**、在**剩下的年限內**，重新計算新的每月還款金額。年限不變，但每月要還的錢變多。
""")

# ------------------------------------------------------------------
st.header("三、股息怎麼算？（對應「股息會跟著市場起伏」）")
st.markdown(r"""
傳統回測常把股息粗略地「自動滾入」，但現實中股息是一筆一筆實際發下來的現金，而且**景氣好時通常發得多、景氣差時會縮水**。

系統用一個簡單的模型來抓這個現象。設基礎的每月配息金額為 $D_0$（由你設定的年化配息率換算），市場從進場到現在的累積漲跌為 $\text{累積報酬}$，那實際發出的股息是：
""")
st.latex(r"D_t = \max\Big(\,0.1 \times D_0,\;\; D_0 \times (1 + \text{累積報酬} \times \beta_{\text{div}})\,\Big)")
st.markdown(r"""
- $\beta_{\text{div}}$ 就是主頁的「**股息跟著市場起伏的程度**」。設 0 表示股息固定不動；設 1 表示股息跟市場連動很大。
- 那個 $\max(\dots, 0.1 \times D_0)$ 是**保底機制**：就算市場崩到谷底，公司至少還是會發出基礎金額的 10%，不會完全停發。
""")

# ------------------------------------------------------------------
st.header("四、每月還款的錢從哪來？（對應「每月還款的錢從哪來」）")
st.markdown(r"""
每個月要繳貸款時，系統按照你排的優先順序，依序動用以下四個來源，直到湊滿這個月的還款為止：

1. **配息資金池**：累積下來、還沒用掉的股息現金。
2. **緩衝金**：開局時預留的備用現金。
3. **變賣資產**：賣掉手上的股票換現金（會扣手續費，崩盤時還可能被賤賣，見下一節）。
4. **本薪（自掏腰包）**：你自己從薪水拿錢出來補，有每月上限。

每個來源只能排進順位一次。不想動用的來源，把多出來的順位選成「（不使用）」即可。

如果排進順位的來源全用光了還是差錢，這個月就**繳不出貸款 → 判定破產**。
""")

st.warning("**重要觀念**：把「本薪」放在順位裡、而且上限設得很高的話，幾乎不會破產——因為一直有薪水在撐。想真正測試「策略本身」扛不扛得住，可以把薪水上限調低，或不要把它放進順位。")

# ------------------------------------------------------------------
st.header("五、崩盤時急著賣股的損失（對應「崩盤時被迫賤賣」）")
st.markdown(r"""
平常賣股票只會損失一點手續費。但在市場大跌、人人都在賣的時候，你很可能只能用更差的價格成交——這叫**流動性折價**。

當某個月的跌幅超過你設定的門檻時，系統會在那個月的賣股成本上，額外加上一筆折價損失。假設這個月還差 $S$ 元才能繳貸款，那實際要賣掉的股票市值是：
""")
st.latex(r"\text{實際需變賣市值} = \frac{S}{1 - (\text{手續費} + \text{額外折價})}")
st.markdown("折價越高，為了湊同樣的錢就得賣掉越多股票，對資產的傷害越大。\n\n一開始用貸款買進股票時，同樣會扣一次手續費。")

# ------------------------------------------------------------------
st.header("六、第二標的沒有真實資料時怎麼辦？（對應「槓桿 ETF 的來回震盪虧損」）")
st.markdown(r"""
第二標的（例如正二）有兩種月份沒有真實報酬可用：**它上市之前**，以及超出歷史資料的**假想未來**。
這些月份系統用第一標的的漲跌去推估它。先從兩者都有資料的重疊期間，估出第二標的對第一標的的敏感度 $\beta$
（第一標的漲 1%，第二標的平均漲幾 %），然後：
""")
st.latex(r"r_B = (1 + r_A)^{\beta} \times e^{-\frac{1}{2}\beta(\beta-1)\sigma_A^{2}} - 1 + \varepsilon")
st.markdown(r"""
- $(1+r_A)^{\beta}$ 是**複利效果**：每日調整的槓桿 ETF 在連續上漲時賺得比「直接乘 $\beta$ 倍」多，連續下跌時賠得比較少
  （第一標的一個月跌 20%，兩倍槓桿是跌 36%，不是 40%）。
- $e^{-\frac{1}{2}\beta(\beta-1)\sigma_A^2}$ 是**波動耗損**：市場來回震盪時悄悄虧掉的部分，$\sigma_A$ 是第一標的的月報酬波動度。
  第一標的當月持平時，第二標的就剛好虧這一段。
- $\varepsilon$ 是隨機誤差，大小取自重疊期間兩者關係的離散程度。

這是槓桿 ETF 文獻的標準近似。兩個效果要一起算：只扣耗損而不算複利，會重複低估。
關掉主頁的開關時，改用最單純的 $r_B = \beta \times r_A + \varepsilon$。
""")
st.info("**不外推超額報酬**：重疊期間第二標的實際上可能長期贏過「第一標的 × β」（例如近幾年的正二）。"
        "系統不假設這個優勢會延續到沒有資料的月份——那段期間它只跟著第一標的走。這是偏保守的假設，適合壓力測試。")
st.warning("只有「沒有真實資料的月份」才用這個公式。有真實資料的月份一律用真實報酬，裡面已經包含複利與耗損，不會重複計算。")

